//! Generation of `docs/commands.md` from the registry
//! (`cargo xtask gen-docs`). A test fails if the file is out of date.

use std::fmt::Write;

use crate::registry::{Action, Command, Query};
use crate::spec::Info;
use crate::step::{BATCH, GO_TO, LIST, REDO, UNDO};

fn section(out: &mut String, infos: &[Info]) {
    for info in infos {
        let _ = writeln!(out, "### `{}`\n", info.name);
        let _ = writeln!(out, "{}\n", info.summary);
        if info.destructive {
            let _ = writeln!(out, "**Destructive**: requires `\"confirm\": true`.\n");
        }
        let schema = serde_json::to_string_pretty(&(info.schema)()).unwrap_or_default();
        let _ = writeln!(
            out,
            "<details><summary>Parameters (JSON schema)</summary>\n"
        );
        let _ = writeln!(out, "```json\n{schema}\n```\n\n</details>\n");
    }
}

/// The full Markdown reference.
pub fn commands_markdown() -> String {
    let mut out = String::new();
    out.push_str(
        "# Commands reference\n\n\
         <!-- Generated by `cargo xtask gen-docs`. Do not edit by hand. -->\n\n\
         Every operation is a JSON object whose `type` is the operation name, \
         followed by its parameters, e.g.\n\n\
         ```json\n{\"type\": \"panel.create_rect\", \"width\": 500, \"height\": 700}\n```\n\n\
         IDs are strings such as `\"panel:2\"`. Lengths are in millimetres.\n\
         Errors are structured: a stable `code`, named `args` and an English `text`.\n\n",
    );
    let _ = writeln!(
        out,
        "## Script steps\n\n\
         A script (CLI `r3d run`) is a JSON array of steps. A step is a command, a query, \
         or one of:\n\n\
         - `{{\"type\": \"{UNDO}\"}}`: undo the last step.\n\
         - `{{\"type\": \"{REDO}\"}}`: redo the last undone step.\n\
         - `{{\"type\": \"{LIST}\"}}`: the steps of the history, oldest first \
         (`steps`, each with its `label`: the command's name, or the batch's), and how \
         many are done (`at`).\n\
         - `{{\"type\": \"{GO_TO}\", \"at\": 3}}`: undo or redo until `at` steps are \
         done (0 undoes them all).\n\
         - `{{\"type\": \"{BATCH}\", \"label\": \"...\", \"commands\": [...]}}`: run \
         commands atomically as one undo step, named `label` in the history (optional, \
         default `batch`); if one fails, none is applied.\n\n\
         Undo, redo and go-to return the panels they changed (`panels`); the app \
         selects them.\n\n\
         A string such as `\"$3.created[0]\"` refers to the result of an earlier step \
         (step 3, 0-based, then the path `.created[0]`; `[n]` indexes arrays, `.name` \
         reads fields). It must be the whole string; `$$` writes a literal `$`. \
         References keep scripts independent of ID allocation.\n"
    );
    out.push_str("## Commands\n\nDocument edits. Every command can be undone.\n\n");
    section(&mut out, &Command::registry());
    out.push_str("## Queries\n\nRead-only. Lengths in mm, areas in mm², rounded to 0.001.\n\n");
    section(&mut out, &Query::registry());
    out.push_str(
        "## Actions\n\nOperations that write files (not undoable). Paths are relative to \
         the project folder and cannot leave it.\n\n",
    );
    section(&mut out, &Action::registry());
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}
